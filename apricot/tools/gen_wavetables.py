#!/usr/bin/env python3
"""Generate apricot/wavetables.h.

Layout: BANKS x FRAMES x TABLE_SIZE samples, uint16, 0..4095 (12-bit DAC).
The OSC 2 Level pot/CV scans through the FRAMES of the active bank.

Run from the repo root:  python3 apricot/tools/gen_wavetables.py
"""
import math
import os
import re

TABLE_SIZE = 1024
FRAMES = 16
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "wavetables.h")
PEACH = os.path.join(HERE, "..", "..", "peach", "peach.ino")


def normalize(samples):
    """Remove DC, scale to full 12-bit range."""
    mean = sum(samples) / len(samples)
    s = [x - mean for x in samples]
    peak = max(abs(x) for x in s) or 1.0
    return [round(2047.5 + 2047.5 * x / peak) for x in s]


def additive(amp_of_harmonic, n_harm):
    """Sum of sines; amp_of_harmonic(k) gives amplitude of harmonic k (1-based)."""
    amps = [(k, amp_of_harmonic(k)) for k in range(1, n_harm + 1)]
    amps = [(k, a) for k, a in amps if a]
    return [
        sum(a * math.sin(2 * math.pi * k * i / TABLE_SIZE) for k, a in amps)
        for i in range(TABLE_SIZE)
    ]


def harmonic(samples, k):
    """Complex DFT coefficient of harmonic k."""
    n = len(samples)
    re_ = sum(x * math.cos(2 * math.pi * k * i / n) for i, x in enumerate(samples))
    im_ = sum(x * math.sin(2 * math.pi * k * i / n) for i, x in enumerate(samples))
    return complex(re_, im_)


def align_phase(samples):
    """Rotate so the fundamental starts like sin(0); avoids cancellation when crossfading."""
    n = len(samples)
    c = harmonic(samples, 1)
    phase = math.atan2(c.real, c.imag)  # phase of fundamental relative to sine
    shift = round(phase / (2 * math.pi) * n)
    return samples[shift:] + samples[:shift] if shift >= 0 else samples[n + shift:] + samples[:n + shift]


def brightness(samples, n_harm=64):
    """Spectral centroid over the first n_harm harmonics."""
    mags = [abs(harmonic(samples, k)) for k in range(1, n_harm + 1)]
    return sum(k * m for k, m in enumerate(mags, 1)) / (sum(mags) or 1.0)


def bank_saw_sweep():
    # Soft saw -> bright saw: harmonic count grows exponentially (4 .. 64).
    frames = []
    for f in range(FRAMES):
        n = round(4 * 16 ** (f / (FRAMES - 1)))
        frames.append(additive(lambda k: 1.0 / k, n))
    return frames


def bank_pwm():
    # Square -> narrow pulse: duty 50% .. 5%, 64 harmonics.
    frames = []
    for f in range(FRAMES):
        duty = 0.5 - 0.45 * f / (FRAMES - 1)
        frames.append(additive(lambda k: math.sin(math.pi * k * duty) / k, 64))
    return frames


def bank_peach_original():
    # The 16 original Peach (Hagiwo) waves, 2048 -> 1024 samples.
    # Phase-aligned and sorted bright -> soft, so neighbouring frames are similar
    # and crossfades between them are smooth (tri and sin end up on the right).
    with open(PEACH) as fh:
        src = fh.read()
    body = src[src.index("wavetable[16][2048]"):]
    rows = re.findall(r"\{([^{}]*)\}", body)[:16]
    frames = []
    for row in rows:
        vals = [int(v) for v in row.replace("\n", " ").split(",") if v.strip()]
        assert len(vals) == 2048, len(vals)
        frames.append([float(v) for v in vals[::2]])
    assert len(frames) == FRAMES
    frames = [align_phase(f) for f in frames]
    return sorted(frames, key=brightness, reverse=True)


def bank_fm():
    # 2-operator FM, modulator ratio 2:1, index 1 .. 8.
    frames = []
    for f in range(FRAMES):
        idx = 1.0 + 7.0 * f / (FRAMES - 1)
        frames.append([
            math.sin(2 * math.pi * i / TABLE_SIZE + idx * math.sin(4 * math.pi * i / TABLE_SIZE))
            for i in range(TABLE_SIZE)
        ])
    return frames


BANKS = [
    ("saw sweep: 4 -> 64 harmonics", bank_saw_sweep),
    ("pwm: square -> 5% pulse", bank_pwm),
    ("peach original 16 waves, phase-aligned, bright -> soft", bank_peach_original),
    ("fm 2:1, index 1 -> 8", bank_fm),
]


def main():
    lines = [
        "// GENERATED by tools/gen_wavetables.py - do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        f"#define WT_BANKS {len(BANKS)}",
        f"#define WT_FRAMES {FRAMES}",
        f"#define WT_SIZE {TABLE_SIZE}",
        "const uint16_t wavetable[WT_BANKS][WT_FRAMES][WT_SIZE] = {",
    ]
    for name, fn in BANKS:
        frames = fn()
        assert len(frames) == FRAMES
        lines.append(f"  {{  // {name}")
        for fr in frames:
            vals = normalize(fr)
            assert len(vals) == TABLE_SIZE and min(vals) >= 0 and max(vals) <= 4095
            lines.append("    {" + ",".join(map(str, vals)) + "},")
        lines.append("  },")
    lines.append("};")
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
